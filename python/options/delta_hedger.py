import numpy as np
from typing import Dict, List, Optional, Tuple
from dataclasses import dataclass, field
from enum import Enum
import time


class HedgeInstrument(Enum):
    SPOT = "spot"
    PERPETUAL = "perpetual"
    FUTURES = "futures"


@dataclass
class HedgeConfig:
    """Configuration for delta hedging behavior."""
    # Rebalancing thresholds
    delta_threshold: float = 0.05  # Rebalance when |delta| > 5% of notional
    min_trade_size: float = 100.0  # Minimum trade size in USD
    max_trade_size: float = 100000.0  # Maximum trade size in USD
    
    # Fee considerations
    maker_fee: float = 0.0002  # 0.02%
    taker_fee: float = 0.0005  # 0.05%
    slippage_estimate: float = 0.0001  # 0.01% estimated slippage
    
    # Risk limits
    max_absolute_delta: float = 0.20  # Hard limit at 20% delta
    gamma_tolerance: float = 0.1  # Allow some gamma exposure
    
    # Instrument preference
    preferred_instrument: HedgeInstrument = HedgeInstrument.PERPETUAL
    
    # Timing
    min_rebalance_interval_ms: int = 1000  # Minimum 1 second between rebalances
    hedge_delay_ms: int = 100  # Delay before executing hedge


@dataclass
class HedgeSignal:
    """Signal generated by the hedging engine."""
    timestamp: float
    current_delta: float
    target_delta: float
    delta_to_hedge: float
    hedge_amount: float  # In base currency (e.g., BTC)
    instrument: HedgeInstrument
    side: str  # "buy" or "sell"
    urgency: str  # "low", "medium", "high"
    estimated_cost: float
    reason: str


@dataclass
class PortfolioState:
    """Current state of the options portfolio."""
    total_delta: float
    total_gamma: float
    total_theta: float
    total_vega: float
    underlying_price: float
    positions: Dict[str, dict] = field(default_factory=dict)


class DeltaHedger:
    """
    Automated delta-neutral hedging engine.
    
    Monitors portfolio delta and executes hedges to maintain neutrality.
    Designed for low-latency operation with fee-aware execution logic.
    """
    
    def __init__(self, config: Optional[HedgeConfig] = None):
        """
        Initialize the delta hedger.
        
        Args:
            config: Hedging configuration (uses defaults if None)
        """
        self.config = config or HedgeConfig()
        self.last_hedge_time = 0.0
        self.cumulative_hedge_pnl = 0.0
        self.hedge_count = 0
        self._hedge_history: List[HedgeSignal] = []
        
        # Pre-allocated buffer for calculations
        self._delta_buffer = np.zeros(100, dtype=np.float32)
    
    def analyze_portfolio(self, portfolio: PortfolioState) -> Optional[HedgeSignal]:
        """
        Analyze portfolio and generate hedge signal if needed.
        
        Args:
            portfolio: Current portfolio state
            
        Returns:
            HedgeSignal if rebalancing is needed, None otherwise
        """
        current_time = time.time() * 1000  # ms
        
        # Check minimum interval
        if current_time - self.last_hedge_time < self.config.min_rebalance_interval_ms:
            return None
        
        # Calculate normalized delta (as % of notional)
        notional = portfolio.underlying_price * abs(portfolio.total_delta)
        normalized_delta = portfolio.total_delta * portfolio.underlying_price / notional if notional > 0 else 0
        
        # Check if delta exceeds threshold
        if abs(normalized_delta) < self.config.delta_threshold:
            return None
        
        # Check hard limit
        if abs(normalized_delta) > self.config.max_absolute_delta:
            urgency = "high"
        elif abs(normalized_delta) > self.config.delta_threshold * 2:
            urgency = "medium"
        else:
            urgency = "low"
        
        # Calculate hedge amount
        delta_to_hedge = -portfolio.total_delta  # Opposite sign to neutralize
        hedge_amount = abs(delta_to_hedge)
        
        # Apply size limits
        hedge_amount_usd = hedge_amount * portfolio.underlying_price
        hedge_amount_usd = max(self.config.min_trade_size, 
                               min(self.config.max_trade_size, hedge_amount_usd))
        hedge_amount = hedge_amount_usd / portfolio.underlying_price
        
        # Determine side
        side = "buy" if delta_to_hedge > 0 else "sell"
        
        # Estimate transaction cost
        estimated_cost = self._estimate_transaction_cost(hedge_amount_usd)
        
        # Check if hedge is worth the cost (benefit > cost)
        benefit = abs(normalized_delta) * notional * 0.01  # Simplified benefit estimate
        if benefit < estimated_cost * 2:  # Require 2x benefit/cost ratio
            if urgency != "high":
                return None
        
        signal = HedgeSignal(
            timestamp=current_time,
            current_delta=normalized_delta,
            target_delta=0.0,
            delta_to_hedge=delta_to_hedge,
            hedge_amount=hedge_amount,
            instrument=self.config.preferred_instrument,
            side=side,
            urgency=urgency,
            estimated_cost=estimated_cost,
            reason=f"Delta {normalized_delta:.2%} exceeds {self.config.delta_threshold:.2%} threshold"
        )
        
        self._hedge_history.append(signal)
        return signal
    
    def _estimate_transaction_cost(self, notional: float) -> float:
        """Estimate total transaction cost including fees and slippage."""
        fee = notional * self.config.taker_fee
        slippage = notional * self.config.slippage_estimate
        return fee + slippage
    
    def execute_hedge(
        self, 
        signal: HedgeSignal,
        execution_func=None
    ) -> bool:
        """
        Execute a hedge based on the signal.
        
        Args:
            signal: Hedge signal to execute
            execution_func: Optional function to call for actual execution
                           Should accept (instrument, side, amount)
                           
        Returns:
            True if hedge was executed successfully
        """
        if execution_func is None:
            # Default: just record the hedge
            self._record_hedge(signal)
            return True
        
        try:
            # Call the provided execution function
            execution_func(
                instrument=signal.instrument.value,
                side=signal.side,
                amount=signal.hedge_amount
            )
            
            self._record_hedge(signal)
            return True
            
        except Exception as e:
            print(f"Hedge execution failed: {e}")
            return False
    
    def _record_hedge(self, signal: HedgeSignal):
        """Record hedge execution for tracking."""
        self.last_hedge_time = signal.timestamp
        self.hedge_count += 1
        
        # Update cumulative PnL (simplified)
        # In production, would track actual fill prices
        self.cumulative_hedge_pnl -= signal.estimated_cost
    
    def get_hedge_statistics(self) -> Dict:
        """Get statistics about hedging activity."""
        if not self._hedge_history:
            return {
                "total_hedges": 0,
                "cumulative_cost": 0.0,
                "avg_hedge_size": 0.0,
                "avg_delta_at_hedge": 0.0,
            }
        
        return {
            "total_hedges": self.hedge_count,
            "cumulative_cost": self.cumulative_hedge_pnl,
            "avg_hedge_size": np.mean([s.hedge_amount for s in self._hedge_history]),
            "avg_delta_at_hedge": np.mean([abs(s.current_delta) for s in self._hedge_history]),
            "hedges_by_urgency": {
                "low": sum(1 for s in self._hedge_history if s.urgency == "low"),
                "medium": sum(1 for s in self._hedge_history if s.urgency == "medium"),
                "high": sum(1 for s in self._hedge_history if s.urgency == "high"),
            }
        }
    
    def reset(self):
        """Reset hedger state."""
        self.last_hedge_time = 0.0
        self.cumulative_hedge_pnl = 0.0
        self.hedge_count = 0
        self._hedge_history.clear()


class MultiAssetDeltaHedger:
    """
    Delta hedger for multi-asset options portfolios.
    
    Handles correlation-aware hedging across multiple underlyings.
    """
    
    def __init__(self, config: Optional[HedgeConfig] = None):
        self.config = config or HedgeConfig()
        self.hedgers: Dict[str, DeltaHedger] = {}
        self.correlation_matrix: Optional[np.ndarray] = None
    
    def add_asset(self, symbol: str):
        """Add an asset to the multi-asset hedger."""
        self.hedgers[symbol] = DeltaHedger(self.config)
    
    def analyze_all(
        self, 
        portfolios: Dict[str, PortfolioState]
    ) -> Dict[str, Optional[HedgeSignal]]:
        """
        Analyze all assets and generate hedge signals.
        
        Args:
            portfolios: Dict mapping symbol to portfolio state
            
        Returns:
            Dict mapping symbol to hedge signal (or None)
        """
        signals = {}
        
        for symbol, portfolio in portfolios.items():
            if symbol not in self.hedgers:
                self.add_asset(symbol)
            
            signals[symbol] = self.hedgers[symbol].analyze_portfolio(portfolio)
        
        return signals
    
    def set_correlations(self, symbols: List[str], corr_matrix: np.ndarray):
        """
        Set correlation matrix for cross-asset hedging optimization.
        
        Args:
            symbols: List of symbols in order
            corr_matrix: NxN correlation matrix
        """
        self.correlation_matrix = corr_matrix
    
    def optimize_cross_asset_hedge(
        self,
        portfolios: Dict[str, PortfolioState],
    ) -> Dict[str, float]:
        """
        Calculate optimal hedge ratios considering correlations.
        
        Uses minimum variance hedge ratio when assets are correlated.
        
        Returns:
            Dict mapping symbol to optimal hedge adjustment factor
        """
        if self.correlation_matrix is None or len(portfolios) < 2:
            # No optimization possible, return 1.0 for all
            return {symbol: 1.0 for symbol in portfolios}
        
        # Simplified: would use full portfolio optimization in production
        adjustments = {}
        
        for symbol in portfolios:
            # Default to full hedge
            adjustments[symbol] = 1.0
        
        return adjustments


def calculate_delta_neutral_quantity(
    option_delta: float,
    option_quantity: int,
    contract_multiplier: float = 1.0,
) -> float:
    """
    Calculate the quantity of underlying needed to delta-hedge an option position.
    
    Args:
        option_delta: Delta of a single option (0 to 1 for calls, -1 to 0 for puts)
        option_quantity: Number of option contracts (positive for long)
        contract_multiplier: Multiplier per contract (e.g., 1 for crypto, 100 for equity)
        
    Returns:
        Quantity of underlying to buy (positive) or sell (negative)
    """
    total_option_delta = option_delta * option_quantity * contract_multiplier
    hedge_quantity = -total_option_delta
    return hedge_quantity


