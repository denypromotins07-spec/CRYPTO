/// Main latency probe for tick-to-trade measurement
pub struct LatencyProbe {
    /// Current active measurements
    active_samples: RwLock<Vec<Arc<Mutex<LatencySample>>>>,
    /// Completed samples for statistics
    completed_samples: Mutex<Vec<u64>>, // Store just latencies for efficiency
    /// Sample counter
    sample_counter: AtomicU64,
    /// UDP sender
    udp_sender: Option<UdpMetricsSender>,
    /// Statistics by symbol
    stats_by_symbol: RwLock<std::collections::HashMap<String, LatencyStatistics>>,
    /// Alert thresholds (nanoseconds)
    alert_threshold_p99: AtomicU64,
    alert_threshold_mean: AtomicU64,
    /// Alerts triggered
    alerts_triggered: AtomicU64,
}

impl LatencyProbe {
    pub fn new(udp_target: Option<&str>) -> Result<Self, std::io::Error> {
        let udp_sender = if let Some(target) = udp_target {
            Some(UdpMetricsSender::new(target, "127.0.0.1:0")?)
        } else {
            None
        };

        Ok(Self {
            active_samples: RwLock::new(Vec::new()),
            completed_samples: Mutex::new(Vec::new()),
            sample_counter: AtomicU64::new(0),
            udp_sender,
            stats_by_symbol: RwLock::new(std::collections::HashMap::new()),
            alert_threshold_p99: AtomicU64::new(1_000_000), // 1ms default
            alert_threshold_mean: AtomicU64::new(100_000),   // 100μs default
            alerts_triggered: AtomicU64::new(0),
        })
    }

    /// Start measuring a new tick-to-trade cycle
    pub fn start_measurement(&self, symbol: String) -> Arc<Mutex<LatencySample>> {
        let mut sample = LatencySample::new(symbol);
        sample.sample_id = self.sample_counter.fetch_add(1, Ordering::Relaxed);
        sample.record_stage(PipelineStage::TickReceived);

        #[cfg(target_arch = "x86_64")]
        {
            sample.cpu_core = Some(unsafe {
                std::arch::x86_64::__readgsdword(0x18) as u32 // TPR on Windows
            });
        }

        let sample_arc = Arc::new(Mutex::new(sample));
        self.active_samples.write().push(sample_arc.clone());
        sample_arc
    }

    /// Complete a measurement and record statistics
    pub fn complete_measurement(&self, sample_arc: &Arc<Mutex<LatencySample>>) {
        let mut sample = sample_arc.lock();
        let latency = sample.calculate_tick_to_trade();
        let symbol = sample.symbol.clone();
        
        // Send via UDP if configured
        if let Some(ref sender) = self.udp_sender {
            let json = serde_json::json!({
                "type": "latency_sample",
                "sample_id": sample.sample_id,
                "symbol": symbol,
                "tick_to_trade_ns": latency,
                "timestamp": sample.timestamp_ns,
            });
            sender.send(json.to_string());
        }

        // Store completed sample
        drop(sample); // Release lock before acquiring others
        
        self.completed_samples.lock().push(latency);

        // Update per-symbol statistics
        let mut stats_map = self.stats_by_symbol.write();
        let samples: Vec<u64> = self.completed_samples.lock().clone();
        let stats = LatencyStatistics::from_samples(&samples);
        stats_map.insert(symbol, stats);

        // Check thresholds
        self.check_thresholds(&stats);

        // Limit stored samples
        let mut completed = self.completed_samples.lock();
        if completed.len() > 10000 {
            *completed = completed.split_off(completed.len() - 10000);
        }

        // Remove from active
        self.active_samples.write().retain(|s| !Arc::ptr_eq(s, sample_arc));
    }

    /// Check alert thresholds
    fn check_thresholds(&self, stats: &LatencyStatistics) {
        let threshold_p99 = self.alert_threshold_p99.load(Ordering::Relaxed);
        let threshold_mean = self.alert_threshold_mean.load(Ordering::Relaxed);

        if stats.p99_ns > threshold_p99 || stats.mean_ns > threshold_mean {
            self.alerts_triggered.fetch_add(1, Ordering::Relaxed);

            // Log alert via UDP
            if let Some(ref sender) = self.udp_sender {
                let json = serde_json::json!({
                    "type": "latency_alert",
                    "p99_ns": stats.p99_ns,
                    "mean_ns": stats.mean_ns,
                    "threshold_p99": threshold_p99,
                    "threshold_mean": threshold_mean,
                    "timestamp": get_time_ns(),
                });
                sender.send(json.to_string());
            }

            eprintln!(
                "LATENCY ALERT: p99={}ns (threshold={}), mean={}ns (threshold={})",
                stats.p99_ns, threshold_p99, stats.mean_ns, threshold_mean
            );
        }
    }

    /// Set alert thresholds
    pub fn set_thresholds(&self, p99_ns: u64, mean_ns: u64) {
        self.alert_threshold_p99.store(p99_ns, Ordering::Relaxed);
        self.alert_threshold_mean.store(mean_ns, Ordering::Relaxed);
    }

    /// Get current statistics for a symbol
    pub fn get_statistics(&self, symbol: &str) -> Option<LatencyStatistics> {
        self.stats_by_symbol.read().get(symbol).cloned()
    }

    /// Get overall statistics
    pub fn get_overall_statistics(&self) -> LatencyStatistics {
        let samples = self.completed_samples.lock();
        LatencyStatistics::from_samples(&samples)
    }

    /// Flush UDP buffer
    pub fn flush_udp(&self) -> usize {
        self.udp_sender.as_ref().map(|s| s.flush()).unwrap_or(0)
    }

    /// Get number of active measurements
    pub fn active_count(&self) -> usize {
        self.active_samples.read().len()
    }

    /// Get alerts triggered count
    pub fn alerts_count(&self) -> u64 {
        self.alerts_triggered.load(Ordering::Relaxed)
    }

    /// Export statistics as JSON string
    pub fn export_json(&self) -> String {
        let overall = self.get_overall_statistics();
        let stats_map = self.stats_by_symbol.read();

        let json = serde_json::json!({
            "overall": overall,
            "by_symbol": *stats_map,
            "active_count": self.active_count(),
            "alerts_triggered": self.alerts_count(),
            "timestamp": get_time_ns(),
        });

        serde_json::to_string(&json).unwrap_or_default()
    }
}

