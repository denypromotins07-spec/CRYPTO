#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_latency_sample() {
        let mut sample = LatencySample::new("BTCUSD".to_string());
        
        sample.record_stage(PipelineStage::TickReceived);
        std::thread::sleep(Duration::from_micros(10));
        sample.record_stage(PipelineStage::SignalGenerated);
        std::thread::sleep(Duration::from_micros(10));
        sample.record_stage(PipelineStage::OrderSent);

        let latency = sample.calculate_tick_to_trade();
        
        assert!(latency > 0);
        println!("Measured latency: {}ns", latency);
    }

    #[test]
    fn test_statistics_calculation() {
        let samples = vec![100, 200, 150, 300, 250, 175, 225, 125, 275, 190];
        let stats = LatencyStatistics::from_samples(&samples);

        assert_eq!(stats.count, 10);
        assert!(stats.min_ns <= stats.max_ns);
        assert!(stats.p50_ns <= stats.p99_ns);
        println!("Stats: {:?}", stats);
    }

    #[test]
    fn test_probe_basic() {
        let probe = LatencyProbe::new(None).unwrap();
        
        let sample = probe.start_measurement("ETHUSD".to_string());
        
        {
            let mut s = sample.lock();
            s.record_stage(PipelineStage::OrderBookUpdated);
            s.record_stage(PipelineStage::RiskCheckPassed);
            s.record_stage(PipelineStage::OrderSent);
        }

        probe.complete_measurement(&sample);

        let stats = probe.get_overall_statistics();
        assert!(stats.count > 0);
        println!("Overall stats: {:?}", stats);
    }
}
