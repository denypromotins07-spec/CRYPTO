//! Latency Probe for Tick-to-Trade Measurement
//! 
//! Measures end-to-end tick-to-trade time using rdtsc CPU cycles.
//! Logs metrics to local time-series DB via non-blocking UDP.

use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::{Duration, Instant};
use std::net::UdpSocket;
use std::collections::VecDeque;

use parking_lot::{Mutex, RwLock};
use serde::{Deserialize, Serialize};

/// High-precision timestamp from rdtsc
#[inline]
fn rdtsc() -> u64 {
    #[cfg(target_arch = "x86_64")]
    {
        unsafe {
            std::arch::x86_64::_rdtsc()
        }
    }
    #[cfg(not(target_arch = "x86_64"))]
    {
        // Fallback for non-x86 architectures
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap()
            .as_nanos() as u64
    }
}

/// Get current time in nanoseconds
#[inline]
fn get_time_ns() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos() as u64
}

// ============================================================================
// Latency Measurement Stages
// ============================================================================

/// Trading pipeline stages for latency measurement
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum PipelineStage {
    /// Market data received from exchange
    TickReceived,
    /// Order book updated
    OrderBookUpdated,
    /// Signal generated by strategy
    SignalGenerated,
    /// Risk check passed
    RiskCheckPassed,
    /// Order sent to exchange
    OrderSent,
    /// Acknowledgment received
    AckReceived,
    /// Fill confirmation
    FillConfirmed,
}

/// Single latency measurement
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LatencySample {
    /// Unique sample ID
    pub sample_id: u64,
    /// Symbol being traded
    pub symbol: String,
    /// Stage transitions
    pub stages: Vec<(PipelineStage, u64)>, // (stage, timestamp_cycles)
    /// Total tick-to-trade time in nanoseconds
    pub tick_to_trade_ns: u64,
    /// System time of sample
    pub timestamp_ns: u64,
    /// CPU core used
    pub cpu_core: Option<u32>,
}

impl LatencySample {
    pub fn new(symbol: String) -> Self {
        Self {
            sample_id: 0,
            symbol,
            stages: Vec::with_capacity(8),
            tick_to_trade_ns: 0,
            timestamp_ns: get_time_ns(),
            cpu_core: None,
        }
    }

    /// Record a stage transition
    pub fn record_stage(&mut self, stage: PipelineStage) {
        self.stages.push((stage, rdtsc()));
    }

    /// Calculate tick-to-trade latency
    pub fn calculate_tick_to_trade(&mut self) -> u64 {
        if self.stages.len() < 2 {
            return 0;
        }

        let tick_time = self.stages[0].1;
        
        // Find order sent time
        let order_sent_time = self.stages
            .iter()
            .find(|(s, _)| *s == PipelineStage::OrderSent)
            .map(|(_, t)| *t)
            .unwrap_or_else(|| self.stages.last().unwrap().1);

        // Convert cycles to nanoseconds (approximate, assuming ~3GHz CPU)
        let cycles_diff = order_sent_time - tick_time;
        self.tick_to_trade_ns = (cycles_diff as f64 * 0.33) as u64; // ~0.33 ns per cycle at 3GHz

        self.tick_to_trade_ns
    }

    /// Get latency between two specific stages
    pub fn get_stage_latency(&self, from: PipelineStage, to: PipelineStage) -> Option<u64> {
        let from_time = self.stages.iter().find(|(s, _)| *s == from)?.1;
        let to_time = self.stages.iter().find(|(s, _)| *s == to)?.1;
        
        if to_time > from_time {
            Some(((to_time - from_time) as f64 * 0.33) as u64)
        } else {
            None
        }
    }
}

