/// Non-blocking UDP sender for metrics
pub struct UdpMetricsSender {
    socket: UdpSocket,
    target_addr: String,
    buffer: Mutex<VecDeque<String>>,
    max_buffer_size: usize,
    dropped_count: AtomicU64,
}

impl UdpMetricsSender {
    pub fn new(target_addr: &str, bind_addr: &str) -> Result<Self, std::io::Error> {
        let socket = UdpSocket::bind(bind_addr)?;
        socket.set_nonblocking(true)?;
        
        Ok(Self {
            socket,
            target_addr: target_addr.to_string(),
            buffer: Mutex::new(VecDeque::with_capacity(1000)),
            max_buffer_size: 10000,
            dropped_count: AtomicU64::new(0),
        })
    }

    /// Queue a metric for sending
    pub fn send(&self, metric: String) {
        let mut buffer = self.buffer.lock();
        
        if buffer.len() >= self.max_buffer_size {
            // Drop oldest if buffer full
            buffer.pop_front();
            self.dropped_count.fetch_add(1, Ordering::Relaxed);
        }
        
        buffer.push_back(metric);
    }

    /// Flush buffered metrics (call periodically)
    pub fn flush(&self) -> usize {
        let mut buffer = self.buffer.lock();
        let mut sent = 0;

        while let Some(metric) = buffer.pop_front() {
            match self.socket.send_to(metric.as_bytes(), &self.target_addr) {
                Ok(_) => sent += 1,
                Err(ref e) if e.kind() == std::io::ErrorKind::WouldBlock => {
                    // Socket not ready, put back and stop
                    buffer.push_front(metric);
                    break;
                }
                Err(_) => {
                    self.dropped_count.fetch_add(1, Ordering::Relaxed);
                }
            }
        }

        sent
    }

    /// Get dropped count
    pub fn dropped_count(&self) -> u64 {
        self.dropped_count.load(Ordering::Relaxed)
    }
}

