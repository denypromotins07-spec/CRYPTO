/// Latency statistics
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct LatencyStatistics {
    /// Sample count
    pub count: u64,
    /// Minimum latency (ns)
    pub min_ns: u64,
    /// Maximum latency (ns)
    pub max_ns: u64,
    /// Mean latency (ns)
    pub mean_ns: u64,
    /// Median latency (ns)
    pub median_ns: u64,
    /// Standard deviation (ns)
    pub std_ns: u64,
    /// 50th percentile (ns)
    pub p50_ns: u64,
    /// 90th percentile (ns)
    pub p90_ns: u64,
    /// 95th percentile (ns)
    pub p95_ns: u64,
    /// 99th percentile (ns)
    pub p99_ns: u64,
    /// 99.9th percentile (ns)
    pub p999_ns: u64,
}

impl LatencyStatistics {
    /// Calculate statistics from samples
    pub fn from_samples(samples: &[u64]) -> Self {
        if samples.is_empty() {
            return Self::default();
        }

        let mut sorted = samples.to_vec();
        sorted.sort_unstable();

        let count = sorted.len() as u64;
        let sum: u64 = sorted.iter().sum();
        let mean = sum / count;

        let min = *sorted.first().unwrap();
        let max = *sorted.last().unwrap();

        // Percentiles
        let p50_idx = (count as f64 * 0.50) as usize;
        let p90_idx = (count as f64 * 0.90) as usize;
        let p95_idx = (count as f64 * 0.95) as usize;
        let p99_idx = (count as f64 * 0.99) as usize;
        let p999_idx = (count as f64 * 0.999) as usize;

        let median = sorted[p50_idx.min(sorted.len() - 1)];
        let p90 = sorted[p90_idx.min(sorted.len() - 1)];
        let p95 = sorted[p95_idx.min(sorted.len() - 1)];
        let p99 = sorted[p99_idx.min(sorted.len() - 1)];
        let p999 = sorted[p999_idx.min(sorted.len() - 1)];

        // Standard deviation
        let variance = sorted.iter()
            .map(|&x| (x as i64 - mean as i64).pow(2) as u64)
            .sum::<u64>() / count;
        let std = (variance as f64).sqrt() as u64;

        Self {
            count,
            min_ns: min,
            max_ns: max,
            mean_ns: mean,
            median_ns: median,
            std_ns: std,
            p50_ns: median,
            p90_ns: p90,
            p95_ns: p95,
            p99_ns: p99,
            p999_ns: p999,
        }
    }
}

